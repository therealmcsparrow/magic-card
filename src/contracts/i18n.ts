/*
 * Contract: i18n. Version 2.0.0.
 * en-US is a FULL shipped table (generated at dev time from en-GB, EN_US_WORDS and reviewed
 * exceptions, then committed); no separate locale files: en-GB, en-US and nl are bundled into each
 * screen's own file; every message must exist in all three locales; compact tables (one string per
 * locale, entries indexed by a build-time number) limit the cost. There is no runtime word list and
 * no lazy nl.
 * Tables live with the bundle that RENDERS the text, not with the file that holds the literal:
 *    - 'card' holds only text a dashboard can render. Editor-only labels in files magic-card.js carries
 *      (CSS property data, animation presets, seasonal scenes, font groups, module descriptions) are
 *      marked lm() and ship in magic-card.js as numbers; their text is in namespace 'labels'.
 *    - A namespace whose call sites are compiled into more than one bundle keeps ONE copy of its tables
 *      in a lazy table chunk (magic-card-i18n-<ns>.js): 'labels' (card editor, studio) and
 *      'icon-library' (icon-library chunk, icon-animator chunk). 'card' stays inline in magic-card.js
 *      (dashboards never wait for a second request); the studio entry keeps its own copy of the card
 *      tables (about 5 KB, see "Where tables live").
 *    - Runtime copies: magic-card.js (reused at 0 B by every chunk below it), the studio entry and the
 *      theme-editor entry (own entries, own copy, own locale state). I18N_RUNTIME_MAX_BYTES is 2,048
 *      per copy.
 *    - Table separator '|' instead of '\n' (Terser writes '\n' as two bytes; saves 3 B per message).
 *    - dashboard: false for icon-library and preset-catalogue.
 * UI copy is British (colour, customise, centre, grey); config keys stay as they are; nl is complete.
 *
 * ── Locales ──
 * en-GB  base and source text: src/<folder>/i18n/en-GB.json, one entry per key (text, note, max, vars).
 * en-US  complete table, src/<folder>/i18n/en-US.json (key -> American text and the hash of the English it was
 *        made from). Generated by tools/i18n-us.mjs from en-GB + EN_US_WORDS + tools/i18n/en-US-exceptions.json
 *        (reviewed by hand); committed; never edited directly (D4).
 * nl     complete table, src/<folder>/i18n/nl.json (key -> Dutch text and hash), written by the localizer.
 * Unsupported languages fall back to en-GB. An empty table cell or a message that does not parse shows the
 * en-GB text; the build writes an en-US or nl cell empty when it equals the en-GB cell.
 * Config keys and values never change (color, background_color, align: center); only labels do.
 *
 * ── Picking the locale (resolveLocale, pure) ──
 * Input: hass.locale.language, else hass.language, else navigator.language. Lower-cased BCP 47.
 *   'en-gb', 'en-au', 'en-nz', 'en-ie', 'en-za', 'en-in'  -> 'en-GB'  (BRITISH_ENGLISH)
 *   'en' and any other 'en-*'                              -> 'en-US'  (HA's "English" is American)
 *   'nl', 'nl-*'                                           -> 'nl'
 *   anything else, empty or malformed                      -> 'en-GB'
 * Each runtime copy keeps its own locale; each bundle calls setI18nLocale(hass) when hass changes: the
 * card (Core card element, replacing setLanguage), the card-editor chunk, the studio entry, the
 * theme-editor entry, the MCU panel. All read the same hass, so they agree.
 * Numbers, dates and times keep src/utils/locale-format.ts (hass.locale number_format, time_format,
 * time_zone); `#` and numeric args use its formatNumber. Never toLocaleString() bare.
 * Every screen root sets lang="<locale>" (WCAG 3.1.2). HA-owned words (states, domains, attributes) come
 * from hass.localize / hass.formatEntityState, never from our tables.
 *
 * ── Ids and the compact format ──
 * Authoring id: a literal key of the namespace's en-GB.json (t('card-editor.design.background.label'); contract
 * i18n-keys.ts). m('key') marks data literals such as icon, preset, theme and CSS option names, rendered later
 * with t(item.name). lm('key') is m() for the 'labels' namespace in files magic-card.js carries; it comes from
 * src/i18n/labels/mark.ts (identity, no tables, no import()), so magic-card.js gets the number and nothing else.
 * Shipped id: a number, the entry's index in the tables. Per namespace, tools/i18n-build.mjs (prebuild, also the
 * vitest setup) builds the tables from the catalogues with tools/i18n/keys.cjs and writes
 * src/<folder>/i18n/messages.gen.ts (git-ignored):
 *   export default ['<en-GB 0>|<en-GB 1>...', '<en-US 0>|...', '<nl 0>|...']  // LOCALES order, '|'
 * Entries are sorted by en-GB text (stable diffs); keys with the same three texts share one entry; an en-US or nl
 * cell equal to its en-GB cell is written empty, which the runtime reads as "use the en-GB cell".
 * tools/i18n-loader.cjs (webpack pre-loader, production and development; tools/i18n/vite-plugin.mjs for vitest)
 * rewrites t('key') to t(17) and m('key') / lm('key') to 17 in that namespace's files, so each text is stored
 * once per locale and no key reaches dist. A first argument that is not a key of its namespace is a build error.
 * Messages may not contain '|' or a newline (D6). At run time a locale's string is split once, on first use; the
 * other two are never touched. The runtime takes numbers only: there is no text-id lookup and no tc().
 * Per namespace module src/<folder>/i18n/index.ts: inline tables
 * `export const { t, tx, m } = i18nFor(ns, tables)`; table chunk
 * `export const { t, tx, m, ready } = i18nForLazy(ns, () => import(/* webpackChunkName: "i18n-<ns>" *\/ './messages.gen'))`.
 * Both create closures only (allowed at module top level of a lazy chunk, lazy-module 1.0.0).
 * Call sites in the runtime lazy chunks (slider, seasonal, markdown, modules-extra) use the 'card'
 * namespace, whose tables live in magic-card.js.
 * `npm run i18n` also writes the git-ignored src/<folder>/i18n/keys.gen.ts (types of the keys and their
 * arguments); `npm run typecheck` runs it first, then tsc --noEmit.
 * Tests resolve a key through tools/i18n/test-msg.ts: msg(key, args?) renders it in the runtime's current
 * locale and msgIndex(key) gives its table index (TestMsg and TestMsgIndex below). A test never writes the
 * text or the number.
 *
 * ── Where tables live ──
 * Rule 1, by renderer: a message goes to 'card' only when a dashboard can render it (card content,
 *   config errors on the card, empty states, screen-reader labels). Text only an editor, the studio or
 *   a picker shows goes to that screen's namespace, or to 'labels' when the literal sits in a file
 *   magic-card.js carries. Proper names and strings that are also identifiers (font family names, CSS
 *   property names shown as code) are not messages (D5 allowlist).
 * Rule 2, one copy: a namespace whose call sites are compiled into exactly one bundle keeps its tables
 *   inline in that bundle. A namespace compiled into several bundles keeps them in its table chunk,
 *   which every one of those bundles import()s (one file, several parents; the preset-catalogue
 *   pattern). A file that the card-editor chunk and the studio entry both compile uses 'labels'.
 *   Exception: 'card' is inline in magic-card.js; the studio entry compiles 28 card files and so carries
 *   a second copy of the card tables (about 5 KB at 64 messages). Reaching magic-card.js's copy through
 *   window.MagicCard would need per-entry module replacement in one webpack compilation (or a second
 *   compilation that emits the shared lazy chunks twice) plus a cross-bundle function API; 5 KB in an
 *   editor-only file costs less.
 * Rule 3, ready before render: a table-chunk namespace renders nothing before ready() resolves. The
 *   card-editor install (loadEditor()) awaits labels.ready() alongside its own setup; the studio entry
 *   awaits labels.ready() before its first render; the icon picker and icon animator await
 *   icon-library ready() where they already await the icon library. ready() resolving false takes that
 *   screen's existing load-failure path (loadEditor() resolves false; the studio shows its load error).
 *
 * ── Message syntax (ICU subset, own parser in src/i18n/runtime.ts, no dependency) ──
 *   {name}                                         argument; numbers through formatNumber
 *   {n, plural, =0 {...} one {# point} other {# points}}   Intl.PluralRules(locale); `other` required
 *   {kind, select, line {...} other {...}}         `other` required
 * Branches may hold {name} arguments, not another plural or select. `=N` and the plural category are chosen from
 * the number as it is shown (rounded to the one fraction digit formatNumber prints); `#` prints that number. No
 * literal braces, no newlines, no '|'. The runtime has no apostrophe quoting. D6 refuses an
 * apostrophe before { } or # in a catalogue, so no message needs it; an apostrophe elsewhere ("Don't") is text.
 * Arguments are inserted as text after the locale text is chosen. Never
 * innerHTML. tx(id, args) returns parts (string | unknown) so lit can render rich arguments, e.g.
 * tx('Delete {name}? This cannot be undone.', { name: html`<strong>..</strong>` }); parts never cross a
 * bundle boundary. ui-kit 1.0.0 holds no strings: every label comes from the caller.
 *
 * ── Drift check (tools/check-i18n.mjs, `npm run i18n -- --check`, release.yml after the size step) ──
 * D1 Extraction: the first argument of t / tx / m / lm is a string literal (no variables, no ${}); it matches
 *    KEY_PATTERN, starts with its namespace and is in en-GB.json. Any other literal is an error.
 * D2 Completeness: every extracted id of a namespace has a non-empty entry in en-US.json and nl.json with
 *    the same argument names and valid plural/select branches; no stale entries. A namespace with
 *    status 'pending' is skipped; the release gate needs every namespace 'complete'
 *    (I18N_RELEASE_STRICT, on).
 * D3 British: no American form from EN_US_WORDS in an en-GB id (allowlist tools/i18n/allow.json, e.g.
 *    the CSS property background-color shown as code); an en-GB word ending -ise / -isation / -our that is
 *    neither in EN_US_WORDS nor allowlisted fails, so new copy extends the list in the same PR.
 * D4 en-US: en-US.json equals tools/i18n-us.mjs output (word list + exceptions); every exception key is an
 *    extracted id and differs from the word-list result; tools/i18n/en-US.golden.txt (every id whose
 *    en-US text differs) is regenerated and reviewed in the PR.
 * D5 No hard-coded user strings: TS/JS AST scan of html`` text and SCANNED_ATTRIBUTES / SCANNED_PROPERTIES
 *    holding letters, outside t/tx/m/lm, src/i18n, src/contracts and the allowlist (Magic Card, YAML,
 *    SVG, MDI, CSS, px, proper names). Per-namespace baseline tools/i18n/baseline.json may only go down;
 *    0 when the slice is done.
 * D6 Syntax: every message in every locale parses; no braces outside the syntax; no newline; no '|'.
 * D7 Placement (import scan plus the production stats.json):
 *    - magic-card.js holds src/i18n/runtime.ts (<= I18N_RUNTIME_MAX_BYTES), the 'card' tables and lm()
 *      numbers; never src/i18n/labels/index.ts, an import() of a table chunk, or any other table.
 *    - Every namespace's tables sit in exactly the file its I18N_MODULES entry names (`bundle` when
 *      tables 'inline', `chunk` when 'chunk'), except the accepted studio copy of 'card'.
 *    - Every call site of a namespace is in a bundle that holds or import()s its tables.
 *    - runtime.ts is in magic-card.js, the studio entry and the theme-editor entry, nowhere else.
 *    - The contract's constants are imported by tools only (src/ imports types).
 * D8 Catalogue (namespaces with an en-GB.json): every entry has a note of NOTE_MIN_CHARS or more, a max, and vars
 *    naming exactly its ICU arguments; no text in any locale is longer than max; the files are sorted and
 *    formatted as i18n-keys.ts says.
 * D9 Stale: an en-US or nl entry whose hash differs from the hash of the current en-GB text fails the release
 *    check unless i18n/waivers.json holds a waiver for that key and hash; a waiver for an unknown key, an old
 *    hash or with an empty reason fails.
 * D10 Removed in 2.0.0 with the legacy count and its file: a call whose first argument is not a key is a D1
 *    error in every namespace. D6 also refuses an apostrophe before { } or # in a catalogue and messages
 *    nested deeper than three brace levels, and limits plural branches to the locale's CLDR categories.
 * Characterization (local vitest; tests/ is not committed): per screen, a text snapshot (text nodes,
 * aria-label, title, placeholder, alt) in en-GB and en-US before extraction, unchanged after extraction,
 * changed only by the reviewed spelling list after the British pass; YAML of the 60 gallery cards unchanged.
 * The text snapshot of the 80 gallery cards is unchanged when labels move to lm() (proof that no
 * dashboard renders a 'labels' message).
 *
 * ── Magic Card Utils ──
 * tools/export-i18n.mjs transpiles src/i18n/runtime.ts to www/mc-i18n.js and the 'mcu-panel' tables to
 * www/mc-i18n-panel.js (same compact strings, keys bound to their indexes by the export tool); both recorded
 * in MCU VENDORED.md with the Magic Card version and SHA-256 (the www/mc-ui-kit.js pattern). The
 * every-page provider magic_card_utils_library.js shows no text and imports neither.
 * Config flow: HA's own rules. translations/en.json (HA's base, American), en-GB.json and nl.json next
 * to strings.json (there is no translations/ folder today).
 *
 * ── Error cases ──
 * unknown locale -> en-GB | empty entry in en-US or nl -> en-GB text | index outside the table -> empty string
 * | malformed message -> en-GB text, console.debug once
 * | missing argument -> empty string, console.debug once | t() of a table-chunk namespace before
 * ready() resolved, or after it resolved false -> empty string, console.debug once (Rule 3 keeps this
 * off screen) | table chunk fails to load -> ready() resolves false, never rejects.
 */

