export const MDI_VIEWBOX = '0 0 24 24';

/** The geometry of a table icon (one filled path, 24 x 24); undefined for other icons. */
export function mdiGeometry(icon: string): IconGeometry | undefined {
  const d = MDI_PATHS[icon];
  return d ? { paths: [d], viewBox: MDI_VIEWBOX } : undefined;
}

/**
 * Put every table icon in an icon geometry cache: the studio and the editor chunk pass icon-source's
 * setIconGeometry, so they split, preview and export these icons without Home Assistant's icon
 * database. The setter is a parameter (this file imports nothing of the card bundle, so a lazy
 * chunk importing it keeps magic-card.js scope-hoisted); `has` skips icons already cached.
 */
export function seedLibraryGeometry(setGeometry: (ref: string, g: IconGeometry) => void, has?: (ref: string) => boolean): void {
  for (const icon of Object.keys(MDI_PATHS)) if (!has?.(icon)) setGeometry(icon, mdiGeometry(icon)!);
}
