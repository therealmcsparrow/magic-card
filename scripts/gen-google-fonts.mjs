// Generates src/google-fonts/catalogue.gen.ts from the public Google Fonts metadata, and with
// --utils <path> the JSON copy used by Magic Card Utils.
// Usage: node scripts/gen-google-fonts.mjs [--utils <path to google_fonts.json>]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const utilsAt = args.includes('--utils') ? args[args.indexOf('--utils') + 1] : undefined;
if (args.includes('--utils') && !utilsAt) throw new Error('--utils needs a path');

const CODES = { 'Sans Serif': 's', Serif: 'e', Display: 'd', Handwriting: 'h', Monospace: 'm' };
const NAME = /^[A-Za-z0-9 ]{1,64}$/;

const res = await fetch('https://fonts.google.com/metadata/fonts');
if (!res.ok) throw new Error(`metadata request failed: ${res.status}`);
const list = (await res.json()).familyMetadataList;
if (!Array.isArray(list)) throw new Error('familyMetadataList missing');

const families = list
  .filter((f) => f.isOpenSource !== false && NAME.test(f.family) && CODES[f.category])
  .sort((a, b) => a.popularity - b.popularity || a.family.localeCompare(b.family))
  .map((f) => ({
    name: f.family,
    code: CODES[f.category],
    weights: Object.keys(f.fonts)
      .filter((k) => /^[1-9]00$/.test(k))
      .map((k) => Number(k))
      .sort((a, b) => a - b),
  }))
  .filter((f) => f.weights.length > 0);

const packed = families.map((f) => `${f.name}\t${f.code}\t${f.weights.map((w) => w / 100).join('')}`).join('\n');
const outDir = resolve(root, 'src/google-fonts');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  resolve(outDir, 'catalogue.gen.ts'),
  `// Generated by scripts/gen-google-fonts.mjs. Do not edit by hand.\nexport const PACKED = ${JSON.stringify(packed)};\n`,
);

if (utilsAt) {
  const aliasSrc = (await import('node:fs')).readFileSync(resolve(outDir, 'aliases.ts'), 'utf8');
  const aliases = {};
  for (const m of aliasSrc.matchAll(/^\s*'([^']+)':\s*'([^']+)',?\s*$/gm)) aliases[m[1]] = m[2];
  const out = { families: Object.fromEntries(families.map((f) => [f.name, f.weights])), aliases };
  mkdirSync(dirname(resolve(utilsAt)), { recursive: true });
  writeFileSync(resolve(utilsAt), `${JSON.stringify(out)}\n`);
}
console.log(`${families.length} families`);
