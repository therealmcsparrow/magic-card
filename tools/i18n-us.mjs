// Writes src/<folder>/i18n/en-US.json of every active namespace from the en-GB ids in the source (or, for a
// namespace with an en-GB.json, from its entries: text and the hash of the English), the EN_US_WORDS list of
// the contract and tools/i18n/en-US-exceptions.json (dev time only; the file is committed and shipped as a
// full table). The exceptions are keyed by the en-GB text. --check compares instead of writing (D4).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const lib = require('./i18n/lib.cjs');
const keys = require('./i18n/keys.cjs');

const GOLDEN = path.join(path.dirname(fileURLToPath(import.meta.url)), 'i18n', 'en-US.golden.txt');
const GOLDEN_HEAD = '# Every message whose en-US text differs from its en-GB text (generated by tools/i18n-us.mjs, reviewed in the PR).\n';

/** en-US.json of a key namespace: { text, hash } per en-GB entry, hash = the hash of the current English. */
function keyCatalogue(n, golden) {
  const toUS = lib.usConverter();
  const us = new Map();
  for (const [key, e] of keys.loadCatalogues(n.dir).gb) {
    const gb = typeof e?.text === 'string' ? e.text : '';
    const text = toUS(gb);
    us.set(key, { text, hash: keys.sourceHash(gb) });
    if (text !== gb) golden.push(`${n.ns}\t${key}\t${text}`);
  }
  return keys.canonicalJson('tr', us);
}

export function run({ check = false } = {}) {
  const { ids, ctxIds, nsList } = lib.extractAll();
  const result = [];
  const golden = [];
  for (const n of nsList) {
    let want;
    if (keys.hasKeys(n.dir)) want = keyCatalogue(n, golden);
    else {
      const us = lib.generateUS(ids.get(n.ns), ctxIds.get(n.ns));
      for (const [id, text] of Object.entries(us)) {
        const gb = ctxIds.get(n.ns).has(id) ? id.slice(ctxIds.get(n.ns).get(id).length + 1) : id;
        if (text !== gb) golden.push(`${n.ns}\t${id}\t${text}`);
      }
      want = lib.stableJson(us);
    }
    const file = path.join(n.dir, 'en-US.json');
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) result.push({ ns: n.ns, ok: have === want });
    else {
      if (have !== want) fs.writeFileSync(file, want);
      result.push({ ns: n.ns, ok: true, changed: have !== want });
    }
  }
  const wantGolden = GOLDEN_HEAD + golden.join('\n') + (golden.length ? '\n' : '');
  const haveGolden = fs.existsSync(GOLDEN) ? fs.readFileSync(GOLDEN, 'utf8') : null;
  if (check) result.push({ ns: 'golden list', ok: haveGolden === wantGolden });
  else if (haveGolden !== wantGolden) fs.writeFileSync(GOLDEN, wantGolden);
  return result;
}

if (process.argv[1]?.endsWith('i18n-us.mjs')) {
  const check = process.argv.includes('--check');
  const res = run({ check });
  for (const r of res) console.log(`${r.ok ? 'ok  ' : 'FAIL'} en-US ${r.ns}${r.changed ? ' (written)' : ''}`);
  process.exit(res.every((r) => r.ok) ? 0 : 1);
}
