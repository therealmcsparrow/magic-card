// Writes THIRD-PARTY-NOTICES.md from the licence files of the installed bundled packages.
// `--check` fails when the file is out of date, or when a production dependency has no entry here.
// No version numbers are written, so dependency bumps don't make the file stale; the SBOM lists versions.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const OUT = `${root}THIRD-PARTY-NOTICES.md`;

// Every production dependency must be listed in a component or in NOT_BUNDLED.
const COMPONENTS = [
  {
    title: 'lit',
    label: 'lit (with lit-html, lit-element, @lit/reactive-element)',
    packages: ['lit', 'lit-html', 'lit-element', '@lit/reactive-element'],
    intro: 'Applies to `lit`, `lit-html`, `lit-element` and `@lit/reactive-element`. Source: https://github.com/lit/lit',
  },
  {
    title: 'marked',
    packages: ['marked'],
    licenceNote: 'MIT (parts BSD-3-Clause, from Markdown by John Gruber)',
    intro: 'Source: https://github.com/markedjs/marked',
  },
  { title: 'js-yaml', packages: ['js-yaml'], intro: 'Source: https://github.com/nodeca/js-yaml' },
  { title: 'swiper', packages: ['swiper'], intro: 'Source: https://github.com/nolimits4web/swiper' },
  {
    title: 'Material Design Icons',
    label: 'Material Design Icons (@mdi/js), icon paths only',
    packages: ['@mdi/js'],
    intro: [
      'Icon paths from `@mdi/js` are bundled in several files in `dist/`, among them `magic-card-icon-animator.js`,',
      '`magic-card-icon-library.js` and `magic-card-editor.js`. Material Design Icons are',
      'maintained by Pictogrammers (https://pictogrammers.com/library/mdi/, source https://github.com/Templarian/MaterialDesign-JS).',
      'The package states that the icons are distributed under the Apache License 2.0, and that some icons are',
      'redistributed under that licence from other sources. The package ships no NOTICE file. The licence',
      'statement from the package follows, then the Apache License 2.0 text.',
    ].join('\n'),
    extra: { heading: 'Apache License 2.0', file: `${root}tools/licenses/Apache-2.0.txt` },
  },
];
const NOT_BUNDLED = []; // production dependencies that never reach dist/, with a reason in a comment

const pkgDir = (name) => `${root}node_modules/${name}/`;
const readPkg = (name) => JSON.parse(readFileSync(`${pkgDir(name)}package.json`, 'utf8'));
const licenceText = (name) => {
  for (const f of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license']) {
    if (existsSync(pkgDir(name) + f)) return readFileSync(pkgDir(name) + f, 'utf8').replace(/\r\n/g, '\n').trimEnd();
  }
  throw new Error(`${name}: no LICENSE file in node_modules`);
};
const fence = (text) => '```\n' + text + '\n```';

function render() {
  const rows = COMPONENTS.map((c) => {
    const licences = [...new Set(c.packages.map((p) => readPkg(p).license))].join(', ');
    return `| ${c.label ?? c.title} | ${c.licenceNote ?? licences} |`;
  });
  const sections = COMPONENTS.map((c) => {
    const texts = [...new Set(c.packages.map(licenceText))];
    let s = `## ${c.title}\n\n${c.intro}\n\n${texts.map(fence).join('\n\n')}\n`;
    if (c.extra) s += `\n### ${c.extra.heading}\n\n${fence(readFileSync(c.extra.file, 'utf8').replace(/\r\n/g, '\n').trimEnd())}\n`;
    return s;
  });
  return [
    '# Third-party notices',
    '',
    '<!-- Generated by tools/third-party-notices.mjs (npm run notices). Do not edit by hand. -->',
    '',
    'Magic Card is released under the MIT License (see [LICENSE](LICENSE)). The files in `dist/` bundle the',
    "third-party software listed below. Each component's copyright notice and licence text is reproduced here",
    'as its licence requires. The exact versions in each release are listed in its `sbom.cdx.json`.',
    '',
    '| Component | Licence |',
    '| --- | --- |',
    ...rows,
    '',
    sections.join('\n'),
  ].join('\n');
}

const listed = new Set([...COMPONENTS.flatMap((c) => c.packages), ...NOT_BUNDLED]);
const missing = Object.keys(JSON.parse(readFileSync(`${root}package.json`, 'utf8')).dependencies ?? {}).filter((d) => !listed.has(d));
if (missing.length) {
  console.error(`FAIL production dependencies with no notices entry: ${missing.join(', ')}. Add them to COMPONENTS (or NOT_BUNDLED) in tools/third-party-notices.mjs`);
  process.exit(1);
}

const text = render();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('FAIL THIRD-PARTY-NOTICES.md is out of date. Run `npm run notices` and commit the result');
    process.exit(1);
  }
  console.log('ok   THIRD-PARTY-NOTICES.md is up to date');
} else {
  writeFileSync(OUT, text);
  console.log('wrote THIRD-PARTY-NOTICES.md');
}
