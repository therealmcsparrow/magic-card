// Writes the Magic Card Utils panel's copy of the UI kit (contract ui-kit 1.0.0, ADR 0030, task UI9):
//   <MCU>/custom_components/magic_card_utils/www/mc-ui-kit.js
// CSS only, no templates and no elements: the editor tokens (Core), the kit's geometry tokens, the kit parts
// and the card editor's shared primitives, as one Lit `css` template, plus the few MDI glyphs the panel draws.
// Reproducible: the output holds no date and no path, so the same sources give the same SHA-256.
//
//   node tools/export-ui-kit.mjs [outFile]    default: ../magic-card-utils/custom_components/magic_card_utils/www/mc-ui-kit.js
//   node tools/export-ui-kit.mjs --check      exit 1 when the file on disk differs from a fresh export
import { registerHooks, createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const DEFAULT_OUT = path.resolve(root, '..', 'magic-card-utils', 'custom_components', 'magic_card_utils', 'www', 'mc-ui-kit.js');

/** The glyphs the panel draws (Material Design Icons, 24 x 24 filled paths): key in the export -> @mdi/js name. */
export const PANEL_GLYPHS = {
  fullscreen: 'mdiFullscreen',
  pencil: 'mdiPencil',
  copy: 'mdiContentCopy',
  delete: 'mdiDeleteOutline',
  close: 'mdiClose',
  info: 'mdiInformationOutline',
  warn: 'mdiAlert',
  error: 'mdiAlertCircleOutline',
  success: 'mdiCheckCircleOutline',
};

const BS = String.fromCharCode(92); // backslash
const TICK = String.fromCharCode(96); // backtick

/** Escape CSS text for a template literal that Lit's `css` reads back unchanged. */
const esc = (s) => s.split(BS).join(BS + BS).split(TICK).join(BS + TICK).split('${').join(BS + '${');

/** Build the file text. Pure apart from reading the sources. */
export async function buildExport() {
  registerHooks(await import(pathToFileURL(path.join(root, 'tools', 'ui-kit-ts-hooks.mjs')).href));
  const system = await import(pathToFileURL(path.join(root, 'src', 'css', 'editor-system.ts')).href);
  const kit = await import(pathToFileURL(path.join(root, 'src', 'ui-kit', 'css', 'index.ts')).href);
  const mdi = require('@mdi/js');
  const version = require(path.join(root, 'package.json')).version;
  const contract = await import(pathToFileURL(path.join(root, 'src', 'contracts', 'ui-kit.ts')).href);

  // Order as in the card editor: tokens, primitives, then the kit's own parts. editorLegacy (the 30 module
  // editors' mc-* classes) and the three element sheets (shadow-root rules of the kit's own elements) stay out.
  const parts = [system.editorTokens, ...(kit.kitTokens ? [kit.kitTokens] : []), kit.editorPrimitives, ...kit.kitCss.filter((c) => c !== kit.kitTokens)];
  const cssText = parts.map((p) => p.cssText.trim()).join('\n');
  const glyphs = Object.entries(PANEL_GLYPHS).map(([k, n]) => {
    if (typeof mdi[n] !== 'string') throw new Error(`@mdi/js has no ${n}`);
    return `  ${k}: ${JSON.stringify(mdi[n])},`;
  });
  const T = TICK;
  return [
    '// GENERATED by tools/export-ui-kit.mjs in the magic-card repo. Do not edit; see VENDORED.md.',
    `// Magic Card UI kit ${version} (contract ui-kit ${contract.UI_KIT_CONTRACT_VERSION} r${contract.UI_KIT_CONTRACT_REVISION}), CSS only, for the panel's shadow root.`,
    'import { css, html } from "./lit-core.min.js";',
    '',
    `export const MC_UI_KIT_VERSION = ${JSON.stringify(version)};`,
    '',
    `/** Put it first in the panel's static styles, before its own layout rules: [mcUiKit, css${T}...${T}]. */`,
    `export const mcUiKit = css${T}`,
    esc(cssText),
    `${T};`,
    '',
    `/** Material Design Icons (Apache-2.0, @mdi/js ${require('@mdi/js/package.json').version}), the paths the panel draws. */`,
    'export const MC_GLYPHS = {',
    ...glyphs,
    '};',
    '',
    '/** An inline glyph drawn in currentColor; size in px. */',
    'export function glyph(name, size = 18) {',
    `  return html${T}<svg class="gl" viewBox="0 0 24 24" width=${'$'}{size} height=${'$'}{size} aria-hidden="true"><path fill="currentColor" d=${'$'}{MC_GLYPHS[name]}></path></svg>${T};`,
    '}',
    '',
  ].join('\n');
}

const sha = (s) => createHash('sha256').update(s).digest('hex');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const out = path.resolve(args.find((a) => !a.startsWith('--')) ?? DEFAULT_OUT);
  const text = await buildExport();
  if (check) {
    const disk = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (disk !== text) {
      console.error(`${out} is stale: run node tools/export-ui-kit.mjs`);
      process.exit(1);
    }
    console.log(`up to date, sha256 ${sha(text)}`);
  } else {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, text, 'utf8');
    console.log(`${out}: ${Buffer.byteLength(text)} B, sha256 ${sha(text)}`);
  }
}
