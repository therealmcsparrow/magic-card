// Exports the i18n runtime for Magic Card Utils (no build step there): writes <out>/mc-i18n.js, the
// transpiled src/i18n/runtime.ts with src/utils/locale-format.ts in front of it (one ES module), and prints
// its SHA-256 for MCU's VENDORED.md (the www/mc-ui-kit.js pattern). Usage: node tools/i18n-export.mjs <out dir>
// The 'mcu-panel' tables (www/mc-i18n-panel.js) are added by slice I9.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const lib = require('./i18n/lib.cjs');

const js = (file) =>
  ts.transpileModule(fs.readFileSync(path.join(lib.SRC, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ES2020, target: ts.ScriptTarget.ES2021 } }).outputText;

export function bundle() {
  const runtime = js('i18n/runtime.ts').replace(/^import \{ formatNumber \} from '[^']+';\r?\n/m, '');
  if (/^import /m.test(runtime)) throw new Error('i18n-export: runtime.ts has an import the exporter does not inline');
  return `// Magic Card i18n runtime (contract i18n 1.0.0 r2), generated by tools/i18n-export.mjs. Do not edit.\n${js('utils/locale-format.ts')}\n${runtime}`;
}

if (process.argv[1]?.endsWith('i18n-export.mjs')) {
  const out = process.argv[2];
  if (!out) {
    console.error('usage: node tools/i18n-export.mjs <out dir>');
    process.exit(1);
  }
  const code = bundle();
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'mc-i18n.js'), code);
  console.log(`mc-i18n.js ${Buffer.byteLength(code)} B sha256 ${crypto.createHash('sha256').update(code).digest('hex')}`);
}
