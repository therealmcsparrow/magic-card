// Exports the i18n runtime for Magic Card Utils (no build step there): writes <out>/mc-i18n.js, the
// transpiled src/i18n/runtime.ts with src/utils/locale-format.ts in front of it (one ES module), and prints
// its SHA-256 for MCU's VENDORED.md (the www/mc-ui-kit.js pattern).
//   node tools/i18n-export.mjs <out dir>                  runtime only
//   node tools/i18n-export.mjs <out dir> --mcu <mcu repo> runtime + the panel tables: also writes
//        <out>/mc-i18n-panel.js and <mcu repo>/i18n/en-US.json, runs the D1-D6 checks on the panel, exit 1 on any error
//   add --check to write nothing and exit 1 when a file differs (stale) or a check fails
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const lib = require('./i18n/lib.cjs');

const js = (file) =>
  ts.transpileModule(fs.readFileSync(path.join(lib.SRC, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ES2020, target: ts.ScriptTarget.ES2021 } }).outputText;

export function bundle() {
  const runtime = js('i18n/runtime.ts').replace(/^import \{[^}]*\} from '(?:\.\.\/utils\/locale-format|\.\/pseudo-hook)';\r?\n/gm, '');
  if (/^import /m.test(runtime)) throw new Error('i18n-export: runtime.ts has an import the exporter does not inline');
  const hook = js('i18n/pseudo-hook.ts').replace(/^import [^\n]*\r?\n/m, '');
  const format = js('utils/locale-format.ts').replace(/^import [^\n]*\r?\n/gm, '');
  return `// Magic Card i18n runtime (contract i18n 2.1.0), generated by tools/i18n-export.mjs. Do not edit.\n${hook}\n${format}\n${runtime}`;
}

const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');

if (process.argv[1]?.endsWith('i18n-export.mjs')) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const mi = args.indexOf('--mcu');
  const mcu = mi >= 0 ? args[mi + 1] : undefined;
  const out = args.find((a, i) => !a.startsWith('--') && i !== mi + 1);
  if (!out || (mi >= 0 && !mcu)) {
    console.error('usage: node tools/i18n-export.mjs <out dir> [--mcu <magic-card-utils repo>] [--check]');
    process.exit(1);
  }
  const files = [[path.join(out, 'mc-i18n.js'), bundle()]];
  let failed = false;
  if (mcu) {
    const { buildPanel } = await import('./i18n-mcu.mjs');
    const p = buildPanel(mcu);
    for (const e of p.errors) console.error('FAIL ' + e);
    failed = p.errors.length > 0;
    files.push([path.join(out, 'mc-i18n-panel.js'), p.tables], [path.join(mcu, 'i18n/en-US.json'), p.usJson]);
    console.log(`mcu-panel: ${p.count} messages, ${p.errors.length} errors`);
  }
  for (const [file, code] of files) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) {
      if (have !== code) {
        console.error(`FAIL ${file} is stale: regenerate with node tools/i18n-export.mjs`);
        failed = true;
      }
    } else if (!failed || path.basename(file) === 'en-US.json') {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, code);
    }
    console.log(`${path.basename(file)} ${Buffer.byteLength(code)} B sha256 ${sha(code)}`);
  }
  process.exit(failed ? 1 : 0);
}
