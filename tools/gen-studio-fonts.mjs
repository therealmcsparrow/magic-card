// Builds the studio fonts: `--subset` fetches the OFL sources and subsets them to fonts/*.woff2 inside a throwaway Docker container;
// without a flag it writes src/ui-kit/fonts/data.ts from the committed fonts/*.woff2 and fonts/OFL.txt. `--check` fails when data.ts is stale.
// The subset command (nothing is installed on the host; --name-IDs='*' keeps the copyright and licence name records):
//   docker run --rm -v "$WORK:/w" -w /w python:3.13-slim sh -c "pip install -q fonttools brotli && pyftsubset <src>.ttf
//     --unicodes='U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2212,U+20AC'
//     --layout-features='kern,liga,calt,tnum,zero' --name-IDs='*' --flavor=woff2 --output-file=<out>.woff2"
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const SOURCE = 'https://raw.githubusercontent.com/google/fonts/main/ofl/';
const UNICODES = 'U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2212,U+20AC';
const FACES = [
  { family: 'MC Space Grotesk', weight: '300 700', source: 'spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf', file: 'space-grotesk.woff2' },
  { family: 'MC Space Mono', weight: '400', source: 'spacemono/SpaceMono-Regular.ttf', file: 'space-mono-400.woff2' },
  { family: 'MC Space Mono', weight: '700', source: 'spacemono/SpaceMono-Bold.ttf', file: 'space-mono-700.woff2' },
];
const DATA = `${root}src/ui-kit/fonts/data.ts`;

async function subset() {
  const work = mkdtempSync(join(tmpdir(), 'mc-fonts-'));
  for (const f of FACES) {
    const res = await fetch(SOURCE + f.source);
    if (!res.ok) throw new Error(`${f.source}: HTTP ${res.status}`);
    writeFileSync(join(work, `${f.file}.ttf`), Buffer.from(await res.arrayBuffer()));
  }
  const run = FACES.map((f) => `pyftsubset ${f.file}.ttf --unicodes='${UNICODES}' --layout-features='kern,liga,calt,tnum,zero' --name-IDs='*' --flavor=woff2 --output-file=${f.file}`).join(' && ');
  execFileSync('docker', ['run', '--rm', '-v', `${work}:/w`, '-w', '/w', 'python:3.13-slim', 'sh', '-c', `pip install -q fonttools brotli && ${run}`], { stdio: 'inherit' });
  mkdirSync(`${root}fonts`, { recursive: true });
  for (const f of FACES) writeFileSync(`${root}fonts/${f.file}`, readFileSync(join(work, f.file)));
}

function render() {
  const licence = readFileSync(`${root}fonts/OFL.txt`, 'utf8').replace(/\r\n/g, '\n').trimEnd().replace(/\*\//g, '* /');
  const faces = FACES.map((f) => `  { family: '${f.family}', weight: '${f.weight}', data: '${readFileSync(`${root}fonts/${f.file}`).toString('base64')}' },`);
  return [
    '// Generated by tools/gen-studio-fonts.mjs from fonts/*.woff2. Do not edit by hand.',
    '// Space Grotesk and Space Mono, latin subsets, as base64 WOFF2 for the card editor chunk and the lazy studio-fonts chunk.',
    '',
    '',
    // inside the array: webpack inlines the constant into the export, which drops a comment above the statement
    'export const STUDIO_FONT_FACES: { family: string; weight: string; data: string }[] = [',
    `/*!\n${licence}\n*/`,
    ...faces,
    '];',
    '',
  ].join('\n');
}

if (process.argv.includes('--subset')) await subset();
for (const f of FACES) if (!existsSync(`${root}fonts/${f.file}`)) throw new Error(`fonts/${f.file} is missing: run with --subset`);
const text = render();
if (process.argv.includes('--check')) {
  const current = existsSync(DATA) ? readFileSync(DATA, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('FAIL src/ui-kit/fonts/data.ts is out of date. Run `node tools/gen-studio-fonts.mjs`');
    process.exit(1);
  }
  console.log('ok   src/ui-kit/fonts/data.ts is up to date');
} else {
  mkdirSync(`${root}src/ui-kit/fonts`, { recursive: true });
  writeFileSync(DATA, text);
  console.log('wrote src/ui-kit/fonts/data.ts');
}
