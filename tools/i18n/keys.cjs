/*
 * Domain keys (contract src/contracts/i18n-keys.ts): the key catalogues of a namespace (en-GB.json, en-US.json,
 * nl.json), source hashes, the compiled tables and their key -> index map, the generated key types, the
 * waivers and the legacy count. A namespace is a key namespace when its i18n folder holds an en-GB.json.
 * Catalogue and waiver files are read into Maps, never merged into plain objects.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const lib = require('./lib.cjs');

const LOCALE_FILES = [
  ['en-US', 'en-US.json'],
  ['nl', 'nl.json'],
];
const HEX = /^[0-9a-f]+$/;

const contract = () => lib.loadKeysContract();

/** First SOURCE_HASH_CHARS hex characters of SHA-256 over the NFC form of the en-GB text. */
function sourceHash(text) {
  return crypto.createHash('sha256').update(text.normalize('NFC'), 'utf8').digest('hex').slice(0, contract().SOURCE_HASH_CHARS);
}

const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** A JSON object file as a Map, or null when the file does not exist. Invalid JSON or a non-object throws. */
function readMap(file) {
  if (!fs.existsSync(file)) return null;
  const raw = fs.readFileSync(file, 'utf8');
  let data;
  try {
    data = JSON.parse(raw);
  } catch (e) {
    throw new Error(`${lib.rel(file)}: not valid JSON (${e.message})`);
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error(`${lib.rel(file)}: not a JSON object`);
  return { map: new Map(Object.entries(data)), raw };
}

/** The catalogues of a namespace folder: { has, gb, us, nl (Maps), raw: { gb, us, nl } (file text or null) }. */
function loadCatalogues(dir) {
  const out = { has: false, gb: new Map(), us: new Map(), nl: new Map(), raw: { gb: null, us: null, nl: null } };
  const gb = readMap(path.join(dir, 'en-GB.json'));
  if (!gb) return out;
  out.has = true;
  out.gb = gb.map;
  out.raw.gb = gb.raw;
  for (const [loc, file] of LOCALE_FILES) {
    const r = readMap(path.join(dir, file));
    const slot = loc === 'en-US' ? 'us' : 'nl';
    if (r) {
      out[slot] = r.map;
      out.raw[slot] = r.raw;
    }
  }
  return out;
}

const hasKeys = (dir) => fs.existsSync(path.join(dir, 'en-GB.json'));

const text = (entry) => (entry && typeof entry.text === 'string' ? entry.text : '');

/** Entries of a key namespace sorted by en-GB text, then key: [{ key, gb, us, nl }] (us and nl fall back to en-GB). */
function sortedEntries(cat) {
  return [...cat.gb.keys()]
    .map((key) => {
      const gb = text(cat.gb.get(key));
      return { key, gb, us: text(cat.us.get(key)) || gb, nl: text(cat.nl.get(key)) || gb };
    })
    .sort((a, b) => byCode(a.gb, b.gb) || byCode(a.key, b.key));
}

/**
 * Compiled tables of a key namespace: rows (en-GB, en-US, nl strings, as lib.genSource takes them) and the
 * key -> index map. Keys whose three texts are all equal share one entry; a shipped en-US or nl cell equal to
 * its en-GB cell is written empty (the run time shows en-GB for an empty cell).
 */
function tablesForKeys(cat) {
  const gb = [];
  const us = [];
  const nl = [];
  const indexOf = new Map();
  const shared = new Map();
  for (const e of sortedEntries(cat)) {
    const sig = [e.gb, e.us, e.nl].join('\u0000');
    if (!shared.has(sig)) {
      shared.set(sig, gb.length);
      gb.push(e.gb);
      us.push(e.us === e.gb ? '' : e.us);
      nl.push(e.nl === e.gb ? '' : e.nl);
    }
    indexOf.set(e.key, shared.get(sig));
  }
  return { rows: [gb, us, nl], indexOf, count: gb.length };
}

const TS_TYPE = { plain: 'string | number', select: 'string | number', plural: 'number' };

/** Source of keys.gen.ts: `export interface Keys` with the argument types of each message and its English as the doc comment. */
function typesSource(cat) {
  const lines = [];
  for (const key of [...cat.gb.keys()].sort(byCode)) {
    const t = text(cat.gb.get(key));
    const { args, error } = lib.parseMessage(t);
    const body = error || !args.size ? (error ? 'Record<string, string | number>' : 'Record<never, never>') : `{ ${[...args.entries()].sort((a, b) => byCode(a[0], b[0])).map(([n, k]) => `${JSON.stringify(n)}: ${TS_TYPE[k]}`).join('; ')} }`;
    lines.push(`  /** ${t.replace(/\*\//g, '*\\/')} */`, `  ${JSON.stringify(key)}: ${body};`);
  }
  return `// generated by tools/i18n-build.mjs (npm run i18n); git-ignored, do not edit\nexport interface Keys {\n${lines.join('\n')}\n}\n`;
}

/** The text a file must hold: sorted by key, fields in contract order, two-space JSON, LF, final newline. */
function canonicalJson(kind, map) {
  const out = {};
  for (const key of [...map.keys()].sort(byCode)) {
    const e = map.get(key) ?? {};
    if (kind === 'gb') {
      const v = { text: e.text, note: e.note, max: e.max };
      if (e.vars && typeof e.vars === 'object') v.vars = Object.fromEntries(Object.keys(e.vars).sort(byCode).map((k) => [k, e.vars[k]]));
      out[key] = v;
    } else out[key] = { text: e.text, hash: e.hash };
  }
  return JSON.stringify(out, null, 2) + '\n';
}

/** The longest text a message can render: every plural and select is replaced by its longest branch; arguments stay as written. */
function longestText(msg) {
  let out = '';
  for (let i = 0; i < msg.length; i++) {
    if (msg[i] !== '{') {
      out += msg[i];
      continue;
    }
    const j = lib.closeAt(msg, i);
    const body = msg.slice(i + 1, j);
    const m = /^\s*\w+\s*,\s*(?:plural|select)\s*,([\s\S]*)$/.exec(body);
    if (!m) out += '{' + body + '}';
    else {
      let r = m[1];
      let best = '';
      for (;;) {
        const q = /^\s*=?\w+\s*\{/.exec(r);
        if (!q) break;
        const open = q[0].length - 1;
        const e = lib.closeAt(r, open);
        const t = longestText(r.slice(open + 1, e));
        if ([...t].length > [...best].length) best = t;
        r = r.slice(e + 1);
      }
      out += best;
    }
    i = j;
  }
  return out;
}

const isPlainObject = (v) => !!v && typeof v === 'object' && !Array.isArray(v);

/** Waivers file as Map `${key}\0${hash}` -> waiver, plus the problems with the file. */
function readWaivers(file = path.join(lib.ROOT, contract().WAIVERS_FILE)) {
  const waivers = new Map();
  const problems = [];
  let data = [];
  if (fs.existsSync(file)) {
    try {
      data = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (e) {
      problems.push(`${contract().WAIVERS_FILE}: not valid JSON (${e.message})`);
    }
  }
  if (!Array.isArray(data)) {
    problems.push(`${contract().WAIVERS_FILE}: not a JSON array`);
    data = [];
  }
  for (const w of data) {
    if (!isPlainObject(w) || typeof w.key !== 'string' || typeof w.hash !== 'string' || typeof w.reason !== 'string') problems.push(`${contract().WAIVERS_FILE}: an entry needs key, hash and reason strings`);
    else waivers.set(`${w.key}\u0000${w.hash}`, w);
  }
  return { waivers, problems };
}

/**
 * Checks one key namespace. Returns [{ rule, level: 'error' | 'warn', msg }].
 *   cat: loadCatalogues result; uses: Map key -> call sites; textSites: text-id calls of the namespace.
 *   spelling: text -> messages (D3). pending: the namespace's translations may be incomplete (D2 reports warnings). strict: stale is an error (D9).
 */
function checkNamespace({ ns, cat, uses = new Map(), textSites = [], waivers = new Map(), pending = false, strict = true, spelling = () => [] }) {
  const { KEY_PATTERN, KEY_MAX_CHARS, NOTE_MIN_CHARS } = contract();
  const out = [];
  const add = (rule, level, msg) => out.push({ rule, level, msg: `${ns} ${msg}` });
  const tr = pending ? 'warn' : 'error';

  const keyProblem = (key) => {
    if (!KEY_PATTERN.test(key)) return 'does not match the key pattern';
    if (key.length > KEY_MAX_CHARS) return `is longer than ${KEY_MAX_CHARS} characters`;
    if (key.split('.')[0] !== ns) return `must start with the namespace "${ns}."`;
    return '';
  };

  for (const [key, sites] of uses) {
    const bad = keyProblem(key);
    if (bad) add('D1', 'error', `"${key}" ${bad} (${sites[0].file}:${sites[0].line})`);
    else if (!cat.gb.has(key)) add('D1', 'error', `"${key}" is not in en-GB.json (${sites[0].file}:${sites[0].line})`);
  }
  for (const s of textSites) add('D10', 'error', `${s.file}:${s.line} ${s.fn}("${s.id.slice(0, 40)}"): a text id in a namespace that has an en-GB.json; use a key`);

  const fileProblems = [
    ['gb', 'en-GB.json'],
    ['us', 'en-US.json'],
    ['nl', 'nl.json'],
  ];
  for (const [slot, name] of fileProblems) {
    if (cat.raw[slot] !== null && cat.raw[slot].replace(/\r\n/g, '\n') !== canonicalJson(slot === 'gb' ? 'gb' : 'tr', cat[slot])) add('D8', 'error', `${name}: not sorted by key, not two-space JSON with a final newline, or an entry has fields the contract does not know`);
  }

  for (const [key, e] of cat.gb) {
    const bad = keyProblem(key);
    if (bad) add('D1', 'error', `en-GB.json "${key}" ${bad}`);
    if (!isPlainObject(e) || typeof e.text !== 'string' || e.text.trim() === '') {
      add('D8', 'error', `"${key}": no text`);
      continue;
    }
    const base = lib.parseMessage(e.text, false, new Map(), { locale: 'en-GB', quotes: true });
    if (base.error) add('D6', 'error', `"${key}" (en-GB): ${base.error}`);
    if (typeof e.note !== 'string' || e.note.trim().length < NOTE_MIN_CHARS) add('D8', 'error', `"${key}": the note (where the text shows and what it does) needs at least ${NOTE_MIN_CHARS} characters`);
    if (!Number.isInteger(e.max) || e.max < 1) add('D8', 'error', `"${key}": max must be a whole number of characters`);
    if (!base.error) {
      const want = [...base.args.keys()].sort(byCode).join(',');
      const have = e.vars === undefined ? '' : isPlainObject(e.vars) ? Object.keys(e.vars).sort(byCode).join(',') : null;
      if (have === null) add('D8', 'error', `"${key}": vars must be an object`);
      else if (have !== want) add('D8', 'error', `"${key}": vars (${have || 'none'}) must describe exactly the arguments of the text (${want || 'none'})`);
      else if (e.vars !== undefined && Object.values(e.vars).some((d) => typeof d !== 'string' || d.trim() === '')) add('D8', 'error', `"${key}": every vars entry needs a description`);
    }
    for (const m of spelling(e.text)) add('D3', 'error', `"${key}": ${m}`);
    if (!uses.has(key)) add('D2', 'error', `en-GB.json: "${key}" is used by no call`);
    const current = sourceHash(e.text);
    for (const [loc, slot, name] of [['en-US', 'us', 'en-US.json'], ['nl', 'nl', 'nl.json']]) {
      const t = cat[slot].get(key);
      if (!isPlainObject(t) || typeof t.text !== 'string' || t.text.trim() === '') {
        add('D2', slot === 'nl' ? tr : 'error', `"${key}": no ${loc} entry`);
        continue;
      }
      const p = lib.parseMessage(t.text, false, new Map(), { locale: loc, quotes: true });
      if (p.error) add('D6', 'error', `"${key}" (${loc}): ${p.error}`);
      else if (!base.error && lib.argSig(p.args) !== lib.argSig(base.args)) add('D2', slot === 'nl' ? tr : 'error', `"${key}" (${loc}): arguments differ (${lib.argNames(p.args)} vs ${lib.argNames(base.args)})`);
      if (Number.isInteger(e.max) && !p.error && [...longestText(t.text)].length > e.max) add('D8', 'error', `"${key}" (${loc}): ${[...longestText(t.text)].length} characters, max is ${e.max}`);
      if (typeof t.hash !== 'string' || t.hash.length !== contract().SOURCE_HASH_CHARS || !HEX.test(t.hash)) add('D9', 'error', `"${key}" (${loc}): the hash is not ${contract().SOURCE_HASH_CHARS} lower-case hex characters`);
      else if (t.hash !== current && !waivers.has(`${key}\u0000${current}`)) add('D9', strict ? 'error' : 'warn', `"${key}" (${loc}) is stale: made from "${t.hash}", the English is now "${current}"; confirm the translation and set its hash, or add a waiver for a typo or punctuation edit`);
    }
    if (Number.isInteger(e.max) && !base.error && [...longestText(e.text)].length > e.max) add('D8', 'error', `"${key}" (en-GB): ${[...longestText(e.text)].length} characters, max is ${e.max}`);
  }
  for (const [slot, name] of [['us', 'en-US.json'], ['nl', 'nl.json']]) {
    for (const key of cat[slot].keys()) if (!cat.gb.has(key)) add('D2', slot === 'nl' ? tr : 'error', `${name}: entry "${key}" is not in en-GB.json`);
  }
  return out;
}

/** Waiver problems (D9): an unknown key, a hash that is not the key's current hash, or an empty reason. */
function checkWaivers(waivers, catalogues) {
  const out = [];
  for (const w of waivers.values()) {
    const owner = [...catalogues].find((c) => c.gb.has(w.key));
    if (!owner) out.push(`D9 waivers: "${w.key}" is not a key of any namespace`);
    else if (w.hash !== sourceHash(text(owner.gb.get(w.key)))) out.push(`D9 waivers: "${w.key}" holds hash ${w.hash}, the English is now ${sourceHash(text(owner.gb.get(w.key)))}; drop the waiver`);
    if (w.reason.trim() === '') out.push(`D9 waivers: "${w.key}" has no reason`);
  }
  return out;
}

/** Legacy count (D10): text-id calls per namespace against tools/i18n/legacy-count.json. */
function legacyCounts(textSites) {
  return Object.fromEntries([...textSites].map(([ns, sites]) => [ns, sites.length]).sort((a, b) => byCode(a[0], b[0])));
}

function compareLegacy(counts, recorded, migrated = new Set()) {
  const out = [];
  for (const [ns, n] of Object.entries(counts)) {
    if (migrated.has(ns)) continue;
    const want = Object.prototype.hasOwnProperty.call(recorded, ns) ? recorded[ns] : 0;
    if (n !== want) out.push(`D10 ${ns}: ${n} text-id calls, ${contract().LEGACY_COUNT_FILE} holds ${want}; ${n > want ? 'use a key for new text' : 'lower the count (--update-legacy-count)'}`);
  }
  for (const ns of Object.keys(recorded)) if (!Object.prototype.hasOwnProperty.call(counts, ns)) out.push(`D10 ${ns}: in ${contract().LEGACY_COUNT_FILE} but not a namespace`);
  return out;
}

module.exports = {
  sourceHash, readMap, loadCatalogues, hasKeys, sortedEntries, tablesForKeys, typesSource, canonicalJson, longestText,
  readWaivers, checkNamespace, checkWaivers, legacyCounts, compareLegacy,
};
