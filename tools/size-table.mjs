// Per-module gzip breakdown of dist/magic-card.js. It builds the card entry in production mode with a
// source map, into a git-ignored directory (.cache/size-table/, never dist/), then attributes every byte of the
// minified file to the source file the map says produced it. Output: the size table between two marker comments in
// docs/size/size-table.md (anything else in that file stays untouched).
// - Same inputs, same bytes out: sorted rows, no dates, no paths from the machine, no timing.
// - Gzip is zlib.gzipSync(buf, { level: 9 }), one shot (the convention of tools/check-dist-size.mjs). It depends on the zlib
//   build, so the table says whether this Node is the one pinned in .nvmrc; only the pinned Node gives authoritative figures.
// - "gzip alone" is each file's attributed text compressed on its own (an upper bound, the sum is larger than the total).
//   "gzip share" is the file's raw share of the real total gzip, so the column sums to the total (an estimate by raw size).
// Usage: node tools/size-table.mjs [--out <file>] [--keep-build] [--check] [--sets <json file>]
//   --out    markdown file to write (default docs/size/size-table.md)
//   --sets   JSON object { name: [source file, ...] }; adds a table of the bytes magic-card.js shrinks by when all files of a set go
//   --check  rebuild and compare with the file as written; exit 1 on any difference (the proof "same table twice")
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, constants, gzipSync } from 'node:zlib';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const args = process.argv.slice(2);
const opt = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const setsFile = opt('--sets');
const outFile = opt('--out') ?? join(ROOT, 'docs', 'size', 'size-table.md');
const BUILD_DIR = join(ROOT, '.cache', 'size-table'); // .cache/ is git-ignored
// source files broken down per top-level declaration and class member
const METHOD_FILES = ['src/card/magic-card.ts', 'src/css/css.ts'];
const BEGIN = '<!-- size-table:begin (generated by tools/size-table.mjs, do not edit by hand) -->';
const END = '<!-- size-table:end -->';

if (!BUILD_DIR.startsWith(join(ROOT, '.cache'))) throw new Error('size-table: build directory outside .cache');

// ---- build -----------------------------------------------------------------
async function build() {
  // generated, git-ignored sources the production build needs (npm run prebuild does the same)
  execFileSync(process.execPath, [join(ROOT, 'tools', 'i18n-build.mjs')], { cwd: ROOT, stdio: 'ignore' });
  rmSync(BUILD_DIR, { recursive: true, force: true });
  mkdirSync(BUILD_DIR, { recursive: true });
  const webpack = require('webpack');
  const config = require(join(ROOT, 'webpack.config.js'))({}, { mode: 'production' });
  config.output = { ...config.output, path: BUILD_DIR, clean: true };
  // hidden: a map file, no sourceMappingURL comment, so magic-card.js is byte-identical to the dist build
  config.devtool = 'hidden-source-map';
  // drop the i18n/entry-graph cache writer: it would overwrite the full-build caches with an entry-only view
  config.plugins = config.plugins.filter((p) => p instanceof webpack.DefinePlugin);
  config.context = ROOT;
  const stats = await new Promise((res, rej) => webpack(config, (e, s) => (e ? rej(e) : res(s))));
  if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
}

// ---- source map ------------------------------------------------------------
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
function decodeMappings(mappings) {
  const lines = [];
  let src = 0;
  let oLine = 0;
  let oCol = 0;
  let name = 0;
  for (const lineStr of mappings.split(';')) {
    const segs = [];
    let col = 0;
    for (const segStr of lineStr.split(',')) {
      if (!segStr) continue;
      const f = [];
      let shift = 0;
      let val = 0;
      for (const ch of segStr) {
        const d = B64.indexOf(ch);
        val += (d & 31) << shift;
        if (d & 32) shift += 5;
        else {
          f.push(val & 1 ? -(val >> 1) : val >> 1);
          val = 0;
          shift = 0;
        }
      }
      col += f[0];
      if (f.length >= 4) {
        src += f[1];
        oLine += f[2];
        oCol += f[3];
        if (f.length >= 5) name += f[4];
        segs.push({ col, src, sLine: oLine, sCol: oCol });
      } else segs.push({ col, src: -1, sLine: -1, sCol: -1 });
    }
    lines.push(segs);
  }
  return lines;
}

/** source id -> { raw bytes, text pieces } for the whole generated file */
function attribute(code, map) {
  let seq = 0;
  const lines = decodeMappings(map.mappings);
  const codeLines = code.split('\n');
  const acc = new Map(); // source index (or -1) -> { bytes, parts }
  const add = (s, text, at) => {
    if (!text) return;
    let e = acc.get(s);
    if (!e) acc.set(s, (e = { bytes: 0, parts: [], pieces: [] }));
    e.bytes += Buffer.byteLength(text);
    e.parts.push(text);
    e.pieces.push({ text, line: at.line, col: at.col, i: seq++ });
  };
  let at = { line: -1, col: -1 };
  let prev = -1; // text with no segment of its own (template-literal continuation lines) belongs to the token before it
  codeLines.forEach((line, i) => {
    const segs = lines[i] ?? [];
    const nl = i < codeLines.length - 1 ? '\n' : '';
    if (!segs.length) return add(prev, line + nl, at);
    add(prev, line.slice(0, segs[0].col), at);
    segs.forEach((s, k) => {
      const end = k + 1 < segs.length ? segs[k + 1].col : line.length;
      if (s.src !== -1) at = { line: s.sLine, col: s.sCol };
      add(s.src, line.slice(s.col, end) + (k + 1 === segs.length ? nl : ''), at);
      prev = s.src;
    });
  });
  return acc;
}

const normalise = (s) => {
  let p = s.replace(/\\/g, '/').replace(/^webpack:\/\/[^/]*\//, '').replace(/^\.\//, '');
  const nm = p.lastIndexOf('node_modules/'); // a symlinked or junctioned node_modules resolves to an absolute path
  if (nm > 0) p = p.slice(nm);
  return p.replace(/\?.*$/, '');
};

/** module group for one source path */
function groupOf(p) {
  if (p === '(generated, no source)' || p.startsWith('webpack/')) return 'webpack runtime and glue';
  const nm = /^(?:.*\/)?node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(p);
  if (nm) {
    const pkg = nm[1];
    if (/^(lit|lit-html|lit-element|@lit|@lit-labs)(\/|$)/.test(pkg) || pkg === 'lit') return 'Lit (lit, lit-html, lit-element, @lit/*)';
    return `node_modules/${pkg}`;
  }
  const m = /^src\/([^/]+)\/(?:([^/]+)\/)?/.exec(p);
  if (!m) return p.startsWith('src/') ? 'src (top-level files)' : p;
  const d = m[1];
  if (d === 'modules' && m[2]) return `src/modules/${m[2]}`;
  return `src/${d}`;
}

// ---- table -----------------------------------------------------------------
const fmt = (n) => n.toLocaleString('en-US');
const pct = (n, t) => ((n * 100) / t).toFixed(2) + '%';
/** brotli as tools/compress-dist.mjs writes it: quality 11, lgwin 22, text mode, size hint = input length */
const br = (buf) =>
  brotliCompressSync(buf, {
    params: {
      [constants.BROTLI_PARAM_QUALITY]: 11,
      [constants.BROTLI_PARAM_LGWIN]: 22,
      [constants.BROTLI_PARAM_MODE]: constants.BROTLI_MODE_TEXT,
      [constants.BROTLI_PARAM_SIZE_HINT]: buf.length,
    },
  }).length;

/** Top-level rules of a CSS template text between two offsets, as ranges named "<declaration>: <selector or at-rule head>". ${...} is opaque. */
function cssRules(text, from, to, decl) {
  const out = [{ start: from - 1, end: from, name: decl + ': (template head)' }];
  let depth = 0;
  let interp = 0;
  let start = from;
  let inComment = false;
  for (let i = from; i < to; i++) {
    const c = text[i];
    if (inComment) {
      if (c === '*' && text[i + 1] === '/') inComment = false;
      continue;
    }
    if (c === '/' && text[i + 1] === '*') inComment = true;
    else if (c === '$' && text[i + 1] === '{') interp++;
    else if (interp && c === '}') interp--;
    else if (interp) continue;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) {
      const head = text.slice(start, i).split('{')[0].replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').trim();
      out.push({ start, end: i + 1, name: decl + ': ' + head.slice(0, 80) });
      start = i + 1;
    }
  }
  out.push({ start, end: to + 1, name: decl + ': (tail)' });
  return out;
}

/** [{ start, end, name }] for the top-level declarations of one TypeScript text; class members are listed as Class.member */
function memberRanges(text, fileName) {
  const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true);
  const out = [];
  const push = (node, name) => out.push({ start: node.getStart(sf), end: node.getEnd(), name });
  for (const st of sf.statements) {
    if (ts.isClassDeclaration(st)) {
      const cls = st.name?.text ?? 'default';
      let cursor = st.getStart(sf);
      const first = st.members[0];
      out.push({ start: cursor, end: first ? first.getFullStart() : st.getEnd(), name: cls + ' (head)' });
      for (const m of st.members) {
        const label = m.name ? m.name.getText(sf) : ts.isConstructorDeclaration(m) ? 'constructor' : ts.isClassStaticBlockDeclaration(m) ? 'static block' : 'member';
        const kind = ts.isGetAccessor(m) ? 'get ' : ts.isSetAccessor(m) ? 'set ' : '';
        out.push({ start: m.getFullStart(), end: m.getEnd(), name: cls + '.' + kind + label });
      }
      out.push({ start: st.getEnd(), end: st.getEnd(), name: cls + ' (tail)' });
    } else if (ts.isVariableStatement(st)) {
      const decl = st.declarationList.declarations.map((d) => d.name.getText(sf)).join(', ');
      push(st, decl);
    } else if (ts.isFunctionDeclaration(st) || ts.isInterfaceDeclaration(st) || ts.isTypeAliasDeclaration(st) || ts.isEnumDeclaration(st)) {
      push(st, st.name?.text ?? 'default');
    } else if (ts.isImportDeclaration(st)) push(st, '(imports)');
    else push(st, '(other statements)');
  }
  return out.sort((a, b) => a.start - b.start);
}

/** per-member breakdown of one source file: raw, gzip share, brotli share, gzip and brotli alone */
function perMember(pieces, text, fileName, loo, cutText) {
  const ranges = memberRanges(text, fileName);
  const starts = [];
  let off = 0;
  for (const l of text.split('\n')) {
    starts.push(off);
    off += l.length + 1;
  }
  const find = (line, col) => {
    if (line < 0) return '(no source position)';
    const o = (starts[line] ?? 0) + col;
    let hit = '(between declarations)';
    for (const r of ranges) {
      if (r.start > o) break;
      if (o < r.end || (r.start === r.end && o === r.start)) hit = r.name;
    }
    return hit;
  };
  const by = new Map();
  for (const pc of pieces) {
    const k = find(pc.line, pc.col);
    const e = by.get(k) ?? { name: k, raw: 0, parts: [], ids: new Set() };
    e.ids.add(pc.i);
    e.raw += Buffer.byteLength(pc.text);
    e.parts.push(pc.text);
    by.set(k, e);
  }
  const rows = [];
  for (const e of by.values()) {
    const joined = e.parts.join('');
    const a = joined.indexOf('`');
    const z = joined.lastIndexOf('`');
    if (e.raw > 5000 && a !== -1 && z > a) {
      // terser maps a whole template literal to its first token, so the rules inside are cut from the minified text
      for (const r of cssRules(joined, a + 1, z, e.name)) {
        const t = joined.slice(r.start, r.end);
        if (!t.trim()) continue;
        const b = Buffer.from(t);
        rows.push({ name: r.name, text: t, raw: Buffer.byteLength(t), gz: gzipSync(b, { level: 9 }).length, br: br(b), ...(b.length >= 150 ? cutText(t) : {}) });
      }
      continue;
    }
    const buf = Buffer.from(joined);
    rows.push({ name: e.name, ids: e.ids, raw: e.raw, gz: gzipSync(buf, { level: 9 }).length, br: br(buf), ...(e.raw >= 150 ? loo(e.ids) : {}) });
  }
  return rows;
}

function render() {
  const code = readFileSync(join(BUILD_DIR, 'magic-card.js'), 'utf8');
  const map = JSON.parse(readFileSync(join(BUILD_DIR, 'magic-card.js.map'), 'utf8'));
  const total = Buffer.byteLength(code);
  const totalGz = gzipSync(Buffer.from(code), { level: 9 }).length;
  const totalBr = br(Buffer.from(code));
  const acc = attribute(code, map);
  const files = [];
  let sum = 0;
  for (const [s, e] of acc) {
    const path = s === -1 ? '(generated, no source)' : normalise(map.sources[s]);
    sum += e.bytes;
    files.push({ path, group: groupOf(path), raw: e.bytes, gz: gzipSync(Buffer.from(e.parts.join('')), { level: 9 }).length, br: br(Buffer.from(e.parts.join(''))), pieces: e.pieces, srcIndex: s });
  }
  if (sum !== total) throw new Error(`size-table: attributed ${sum} B but the file is ${total} B`);
  // merge rows that normalise to one path (query-string variants), then add the gzip share
  const byPath = new Map();
  for (const f of files) {
    const o = byPath.get(f.path);
    if (o) {
      o.raw += f.raw;
      o.gz += f.gz;
      o.br += f.br;
      o.pieces = o.pieces.concat(f.pieces);
    } else byPath.set(f.path, { ...f });
  }
  const rows = [...byPath.values()];
  // bytes the file's text costs inside the whole: total compressed size minus the size of the file with those pieces cut out
  const ordered = rows.flatMap((r) => r.pieces).sort((a, b) => a.i - b.i);
  const loo = (ids, texts = []) => {
    let kept = ordered.filter((pc) => !ids.has(pc.i)).map((pc) => pc.text).join('');
    for (const t of texts) kept = kept.replace(t, '');
    const rest = Buffer.from(kept);
    return { gzCut: totalGz - gzipSync(rest, { level: 9 }).length, brCut: totalBr - br(rest) };
  };
  const cutText = (t) => {
    const at = code.indexOf(t);
    if (at === -1) return {};
    const rest = Buffer.from(code.slice(0, at) + code.slice(at + t.length));
    return { gzCut: totalGz - gzipSync(rest, { level: 9 }).length, brCut: totalBr - br(rest) };
  };
  for (const r of rows) if (r.raw >= 800) Object.assign(r, loo(new Set(r.pieces.map((pc) => pc.i))));
  let shareLeft = totalGz;
  let brLeft = totalBr;
  const sorted = [...rows].sort((a, b) => b.raw - a.raw || (a.path < b.path ? -1 : 1));
  sorted.forEach((r, i) => {
    r.share = i === sorted.length - 1 ? shareLeft : Math.round((r.raw * totalGz) / total);
    shareLeft -= r.share;
    r.brShare = i === sorted.length - 1 ? brLeft : Math.round((r.raw * totalBr) / total);
    brLeft -= r.brShare;
  });
  const groups = new Map();
  for (const r of rows) {
    const g = groups.get(r.group) ?? { group: r.group, files: 0, raw: 0, share: 0, brShare: 0, gz: 0 };
    g.files += 1;
    g.raw += r.raw;
    g.share += r.share;
    g.brShare += r.brShare;
    g.gz += r.gz;
    groups.set(r.group, g);
  }
  const gs = [...groups.values()].sort((a, b) => b.raw - a.raw || (a.group < b.group ? -1 : 1));

  const nvmrc = readFileSync(join(ROOT, '.nvmrc'), 'utf8').trim();
  const authoritative = process.versions.node === nvmrc;
  const caps = JSON.parse(readFileSync(join(ROOT, 'tools', 'size-caps.json'), 'utf8'));
  const recorded = caps.gzip?.zlib;
  const zlibOk = !recorded || process.versions.zlib === recorded;
  const auth = authoritative && zlibOk;
  const L = [];
  L.push(BEGIN, '', '## Size table: dist/magic-card.js by module', '');
  L.push(`Built by \`node tools/size-table.mjs\`: production build (all entries, as released) with a source map in \`.cache/size-table/\`, every minified byte attributed to the source file the map names.`);
  L.push('');
  L.push(`- Pinned Node (.nvmrc): ${nvmrc}. This table was made on Node ${process.versions.node}, zlib ${process.versions.zlib}: **${auth ? 'authoritative' : 'NOT AUTHORITATIVE (off the pinned Node or zlib), gzip figures may differ by a few bytes'}**.`);
  L.push(`- Gzip: level 9, one-shot \`gzipSync\`. Total: **${fmt(totalGz)} B gzip**, **${fmt(totalBr)} B brotli** (quality 11, as compress-dist writes it), ${fmt(total)} B raw (minified), ${fmt(rows.length)} attributed files.`);
  L.push('- Source of the figures: a build of a clean LF checkout (`git archive HEAD`), as CI builds. A working copy with CRLF template strings (Windows autocrlf) gives a few bytes more.');
  L.push('- cut = the bytes the whole file shrinks by when that text is removed from magic-card.js (total minus the compressed rest; files of 800 B raw or more, declarations of 150 B or more). It is the real saving of moving the text out, the best guide for ranking; the shares are by raw size and over-state highly repetitive text such as CSS.');
  L.push('- raw = minified bytes attributed to the file or group. gzip share = that raw share of the real total gzip (sums to the total). gzip alone = the attributed text compressed on its own (upper bound; the sum is above the total).');
  L.push('');
  L.push('### By module group', '', '| Group | Files | Raw B | % raw | Gzip share B | % gzip | Brotli share B | Gzip alone B |', '|---|---:|---:|---:|---:|---:|---:|---:|');
  for (const g of gs) L.push(`| ${g.group} | ${g.files} | ${fmt(g.raw)} | ${pct(g.raw, total)} | ${fmt(g.share)} | ${pct(g.share, totalGz)} | ${fmt(g.brShare)} | ${fmt(g.gz)} |`);
  L.push(`| **Total** | ${rows.length} | ${fmt(total)} | 100.00% | ${fmt(totalGz)} | 100.00% | ${fmt(totalBr)} | |`);
  L.push('', '### By source file', '', '| Source file | Group | Raw B | Gzip share B | Brotli share B | Gzip alone B | Brotli alone B | Gzip cut B | Brotli cut B |', '|---|---|---:|---:|---:|---:|---:|---:|---:|');
  for (const r of sorted) L.push(`| ${r.path} | ${r.group} | ${fmt(r.raw)} | ${fmt(r.share)} | ${fmt(r.brShare)} | ${fmt(r.gz)} | ${fmt(r.br)} | ${r.gzCut === undefined ? '' : fmt(r.gzCut)} | ${r.brCut === undefined ? '' : fmt(r.brCut)} |`);
  const memo = new Map();
  const members = (r, file) => {
    if (!memo.has(file)) memo.set(file, perMember(r.pieces, map.sourcesContent?.[r.srcIndex] ?? readFileSync(join(ROOT, file), 'utf8'), file, loo, cutText));
    return memo.get(file);
  };
  if (setsFile) {
    const sets = JSON.parse(readFileSync(setsFile, 'utf8'));
    L.push('', '### Sets of source files', '', 'Each row: the bytes magic-card.js shrinks by when every file of the set is removed from it together (gzip level 9, brotli 11).', '');
    L.push('| Set | Files | Raw B | Gzip cut B | Brotli cut B |', '|---|---:|---:|---:|---:|');
    for (const [name, paths] of Object.entries(sets)) {
      // an entry is a source file, or "file::Declaration" for one declaration of a file in METHOD_FILES
      const ids = new Set();
      const texts = [];
      let raw = 0;
      let found = 0;
      for (const item of paths) {
        const cut = item.indexOf('::');
        const file = cut === -1 ? item : item.slice(0, cut);
        const decl = cut === -1 ? undefined : item.slice(cut + 2);
        const r = rows.find((x) => x.path === file);
        if (!r) continue;
        if (!decl) {
          found++;
          raw += r.raw;
          r.pieces.forEach((pc) => ids.add(pc.i));
          continue;
        }
        const all = members(r, file);
        // a declaration name, or /regex/ over the rule names of a split CSS template
        const re = decl.startsWith('/') ? new RegExp(decl.slice(1, decl.lastIndexOf('/')), decl.slice(decl.lastIndexOf('/') + 1)) : null;
        for (const m of all.filter((x) => (re ? re.test(x.name) : x.name === decl))) {
          found++;
          raw += m.raw;
          m.ids?.forEach((i) => ids.add(i));
          if (m.text) texts.push(m.text);
        }
      }
      const c = loo(ids, texts);
      L.push(`| ${name} | ${found} of ${paths.length} | ${fmt(raw)} | ${fmt(c.gzCut)} | ${fmt(c.brCut)} |`);
    }
  }
  for (const mf of METHOD_FILES) {
    const r = rows.find((x) => x.path === mf);
    if (!r) continue;
    const ms = [...members(r, mf)].sort((a, b) => b.raw - a.raw || (a.name < b.name ? -1 : 1));
    L.push('', `### Per declaration: ${mf}`, '', `Whole file: ${fmt(r.raw)} B raw, ${fmt(r.share)} B gzip share, ${fmt(r.brShare)} B brotli share. Shares are the member's raw share of the file's share.`, '');
    L.push('| Declaration | Raw B | Gzip share B | Brotli share B | Gzip alone B | Brotli alone B | Gzip cut B | Brotli cut B |', '|---|---:|---:|---:|---:|---:|---:|---:|');
    for (const m of ms) L.push(`| ${m.name} | ${fmt(m.raw)} | ${fmt(Math.round((m.raw * r.share) / r.raw))} | ${fmt(Math.round((m.raw * r.brShare) / r.raw))} | ${fmt(m.gz)} | ${fmt(m.br)} | ${m.gzCut === undefined ? '' : fmt(m.gzCut)} | ${m.brCut === undefined ? '' : fmt(m.brCut)} |`);
  }
  L.push('', END);
  return L.join('\n') + '\n';
}

function merge(existing, block) {
  const i = existing.indexOf(BEGIN);
  const j = existing.indexOf(END);
  if (i !== -1 && j > i) return existing.slice(0, i) + block.trimEnd() + existing.slice(j + END.length);
  const head = existing.trimEnd();
  return (head ? head + '\n\n' : '# Size measurements\n\n') + block;
}

await build();
const block = render();
const existing = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
const next = merge(existing, block);
if (args.includes('--check')) {
  if (next !== existing) {
    console.error(`size-table --check: ${outFile} differs from a fresh build`);
    process.exitCode = 1;
  } else console.log('size-table --check: identical');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log(`size-table: wrote ${outFile}`);
}
if (!args.includes('--keep-build')) rmSync(BUILD_DIR, { recursive: true, force: true });
