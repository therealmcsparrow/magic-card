// Per-module gzip breakdown of dist/magic-card.js (build plan S0.2). It builds the card entry in production mode with a
// source map, into a git-ignored directory (.cache/size-table/, never dist/, webpack.M-SEC3), then attributes every byte of the
// minified file to the source file the map says produced it. Output: the size table between two marker comments in
// docs/size/S0.md (the rest of that file belongs to the S0.5 trace and stays untouched).
// - Same inputs, same bytes out: sorted rows, no dates, no paths from the machine, no timing.
// - Gzip is zlib.gzipSync(buf, { level: 9 }), one shot (the S0.1 convention, tools/check-dist-size.mjs). It depends on the zlib
//   build, so the table says whether this Node is the one pinned in .nvmrc; only the pinned Node gives authoritative figures.
// - "gzip alone" is each file's attributed text compressed on its own (an upper bound, the sum is larger than the total).
//   "gzip share" is the file's raw share of the real total gzip, so the column sums to the total (an estimate by raw size).
// Usage: node tools/size-table.mjs [--out <file>] [--keep-build] [--check]
//   --out    markdown file to write (default docs/size/S0.md)
//   --check  rebuild and compare with the file as written; exit 1 on any difference (the proof "same table twice")
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const args = process.argv.slice(2);
const opt = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const outFile = opt('--out') ?? join(ROOT, 'docs', 'size', 'S0.md');
const BUILD_DIR = join(ROOT, '.cache', 'size-table'); // .cache/ is git-ignored
const BEGIN = '<!-- size-table:begin (generated by tools/size-table.mjs, do not edit by hand) -->';
const END = '<!-- size-table:end -->';

if (!BUILD_DIR.startsWith(join(ROOT, '.cache'))) throw new Error('size-table: build directory outside .cache');

// ---- build -----------------------------------------------------------------
async function build() {
  // generated, git-ignored sources the production build needs (npm run prebuild does the same)
  execFileSync(process.execPath, [join(ROOT, 'tools', 'i18n-build.mjs')], { cwd: ROOT, stdio: 'ignore' });
  rmSync(BUILD_DIR, { recursive: true, force: true });
  mkdirSync(BUILD_DIR, { recursive: true });
  const webpack = require('webpack');
  const config = require(join(ROOT, 'webpack.config.js'))({}, { mode: 'production' });
  config.output = { ...config.output, path: BUILD_DIR, clean: true };
  // hidden: a map file, no sourceMappingURL comment, so magic-card.js is byte-identical to the dist build
  config.devtool = 'hidden-source-map';
  // drop the i18n/entry-graph cache writer: it would overwrite the full-build caches with an entry-only view
  config.plugins = config.plugins.filter((p) => p instanceof webpack.DefinePlugin);
  config.context = ROOT;
  const stats = await new Promise((res, rej) => webpack(config, (e, s) => (e ? rej(e) : res(s))));
  if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
}

// ---- source map ------------------------------------------------------------
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
function decodeMappings(mappings) {
  const lines = [];
  let src = 0;
  let oLine = 0;
  let oCol = 0;
  let name = 0;
  for (const lineStr of mappings.split(';')) {
    const segs = [];
    let col = 0;
    for (const segStr of lineStr.split(',')) {
      if (!segStr) continue;
      const f = [];
      let shift = 0;
      let val = 0;
      for (const ch of segStr) {
        const d = B64.indexOf(ch);
        val += (d & 31) << shift;
        if (d & 32) shift += 5;
        else {
          f.push(val & 1 ? -(val >> 1) : val >> 1);
          val = 0;
          shift = 0;
        }
      }
      col += f[0];
      if (f.length >= 4) {
        src += f[1];
        oLine += f[2];
        oCol += f[3];
        if (f.length >= 5) name += f[4];
        segs.push({ col, src });
      } else segs.push({ col, src: -1 });
    }
    lines.push(segs);
  }
  return lines;
}

/** source id -> { raw bytes, text pieces } for the whole generated file */
function attribute(code, map) {
  const lines = decodeMappings(map.mappings);
  const codeLines = code.split('\n');
  const acc = new Map(); // source index (or -1) -> { bytes, parts }
  const add = (s, text) => {
    if (!text) return;
    let e = acc.get(s);
    if (!e) acc.set(s, (e = { bytes: 0, parts: [] }));
    e.bytes += Buffer.byteLength(text);
    e.parts.push(text);
  };
  let prev = -1; // text with no segment of its own (template-literal continuation lines) belongs to the token before it
  codeLines.forEach((line, i) => {
    const segs = lines[i] ?? [];
    const nl = i < codeLines.length - 1 ? '\n' : '';
    if (!segs.length) return add(prev, line + nl);
    add(prev, line.slice(0, segs[0].col));
    segs.forEach((s, k) => {
      const end = k + 1 < segs.length ? segs[k + 1].col : line.length;
      add(s.src, line.slice(s.col, end) + (k + 1 === segs.length ? nl : ''));
      prev = s.src;
    });
  });
  return acc;
}

const normalise = (s) => {
  let p = s.replace(/\\/g, '/').replace(/^webpack:\/\/[^/]*\//, '').replace(/^\.\//, '');
  const nm = p.lastIndexOf('node_modules/'); // a symlinked or junctioned node_modules resolves to an absolute path
  if (nm > 0) p = p.slice(nm);
  return p.replace(/\?.*$/, '');
};

/** module group for one source path */
function groupOf(p) {
  if (p === '(generated, no source)' || p.startsWith('webpack/')) return 'webpack runtime and glue';
  const nm = /^(?:.*\/)?node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(p);
  if (nm) {
    const pkg = nm[1];
    if (/^(lit|lit-html|lit-element|@lit|@lit-labs)(\/|$)/.test(pkg) || pkg === 'lit') return 'Lit (lit, lit-html, lit-element, @lit/*)';
    return `node_modules/${pkg}`;
  }
  const m = /^src\/([^/]+)\/(?:([^/]+)\/)?/.exec(p);
  if (!m) return p.startsWith('src/') ? 'src (top-level files)' : p;
  const d = m[1];
  if (d === 'modules' && m[2]) return `src/modules/${m[2]}`;
  return `src/${d}`;
}

// ---- table -----------------------------------------------------------------
const fmt = (n) => n.toLocaleString('en-US');
const pct = (n, t) => ((n * 100) / t).toFixed(2) + '%';

function render() {
  const code = readFileSync(join(BUILD_DIR, 'magic-card.js'), 'utf8');
  const map = JSON.parse(readFileSync(join(BUILD_DIR, 'magic-card.js.map'), 'utf8'));
  const total = Buffer.byteLength(code);
  const totalGz = gzipSync(Buffer.from(code), { level: 9 }).length;
  const acc = attribute(code, map);
  const files = [];
  let sum = 0;
  for (const [s, e] of acc) {
    const path = s === -1 ? '(generated, no source)' : normalise(map.sources[s]);
    sum += e.bytes;
    files.push({ path, group: groupOf(path), raw: e.bytes, gz: gzipSync(Buffer.from(e.parts.join('')), { level: 9 }).length });
  }
  if (sum !== total) throw new Error(`size-table: attributed ${sum} B but the file is ${total} B`);
  // merge rows that normalise to one path (query-string variants), then add the gzip share
  const byPath = new Map();
  for (const f of files) {
    const o = byPath.get(f.path);
    if (o) {
      o.raw += f.raw;
      o.gz += f.gz;
    } else byPath.set(f.path, { ...f });
  }
  const rows = [...byPath.values()];
  let shareLeft = totalGz;
  const sorted = [...rows].sort((a, b) => b.raw - a.raw || (a.path < b.path ? -1 : 1));
  sorted.forEach((r, i) => {
    r.share = i === sorted.length - 1 ? shareLeft : Math.round((r.raw * totalGz) / total);
    shareLeft -= r.share;
  });
  const groups = new Map();
  for (const r of rows) {
    const g = groups.get(r.group) ?? { group: r.group, files: 0, raw: 0, share: 0, gz: 0 };
    g.files += 1;
    g.raw += r.raw;
    g.share += r.share;
    g.gz += r.gz;
    groups.set(r.group, g);
  }
  const gs = [...groups.values()].sort((a, b) => b.raw - a.raw || (a.group < b.group ? -1 : 1));

  const nvmrc = readFileSync(join(ROOT, '.nvmrc'), 'utf8').trim();
  const authoritative = process.versions.node === nvmrc;
  const caps = JSON.parse(readFileSync(join(ROOT, 'tools', 'size-caps.json'), 'utf8'));
  const recorded = caps.gzip?.zlib;
  const zlibOk = !recorded || process.versions.zlib === recorded;
  const auth = authoritative && zlibOk;
  const L = [];
  L.push(BEGIN, '', '## Size table: dist/magic-card.js by module (S0.2)', '');
  L.push(`Built by \`node tools/size-table.mjs\`: production build (all entries, as released) with a source map in \`.cache/size-table/\`, every minified byte attributed to the source file the map names.`);
  L.push('');
  L.push(`- Pinned Node (.nvmrc): ${nvmrc}. This table was made on Node ${process.versions.node}, zlib ${process.versions.zlib}: **${auth ? 'authoritative' : 'NOT AUTHORITATIVE (off the pinned Node or zlib), gzip figures may differ by a few bytes'}**.`);
  L.push(`- Gzip: level 9, one-shot \`gzipSync\`. Total: **${fmt(totalGz)} B gzip**, ${fmt(total)} B raw (minified), ${fmt(rows.length)} attributed files.`);
  L.push('- Source of the figures: a build of a clean LF checkout (`git archive HEAD`), as CI builds. A working copy with CRLF template strings (Windows autocrlf) gives a few bytes more.');
  L.push('- raw = minified bytes attributed to the file or group. gzip share = that raw share of the real total gzip (sums to the total). gzip alone = the attributed text compressed on its own (upper bound; the sum is above the total).');
  L.push('');
  L.push('### By module group', '', '| Group | Files | Raw B | % raw | Gzip share B | % gzip | Gzip alone B |', '|---|---:|---:|---:|---:|---:|---:|');
  for (const g of gs) L.push(`| ${g.group} | ${g.files} | ${fmt(g.raw)} | ${pct(g.raw, total)} | ${fmt(g.share)} | ${pct(g.share, totalGz)} | ${fmt(g.gz)} |`);
  L.push(`| **Total** | ${rows.length} | ${fmt(total)} | 100.00% | ${fmt(totalGz)} | 100.00% | |`);
  L.push('', '### By source file', '', '| Source file | Group | Raw B | Gzip share B | Gzip alone B |', '|---|---|---:|---:|---:|');
  for (const r of sorted) L.push(`| ${r.path} | ${r.group} | ${fmt(r.raw)} | ${fmt(r.share)} | ${fmt(r.gz)} |`);
  L.push('', END);
  return L.join('\n') + '\n';
}

function merge(existing, block) {
  const i = existing.indexOf(BEGIN);
  const j = existing.indexOf(END);
  if (i !== -1 && j > i) return existing.slice(0, i) + block.trimEnd() + existing.slice(j + END.length);
  const head = existing.trimEnd();
  return (head ? head + '\n\n' : '# Size measurements (build plan S0)\n\n') + block;
}

await build();
const block = render();
const existing = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
const next = merge(existing, block);
if (args.includes('--check')) {
  if (next !== existing) {
    console.error(`size-table --check: ${outFile} differs from a fresh build`);
    process.exitCode = 1;
  } else console.log('size-table --check: identical');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log(`size-table: wrote ${outFile}`);
}
if (!args.includes('--keep-build')) rmSync(BUILD_DIR, { recursive: true, force: true });
